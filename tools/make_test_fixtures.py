#!/usr/bin/env python3
"""
Extract two real clips (one bonafide, one synthetic) for the on-device test.

The old fixtures were generated by make_samples.py, i.e. the same synthesiser the
demo model was trained on. That made the instrumented test circular. These come
from garystafford/deepfake-audio-detection (CC-BY-4.0), a corpus the detector is
*evaluated* on but never trained on, so the test exercises the real feature path.

  python tools/make_test_fixtures.py
"""

from __future__ import annotations

import os
from math import gcd

import numpy as np
import pyarrow.parquet as pq
import soundfile as sf
from scipy.signal import resample_poly

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_DIR = os.path.join(ROOT, "data", "deepfake_audio_detection")
OUT_DIR = os.path.join(ROOT, "app", "src", "androidTest", "assets")
SR = 16_000
SECONDS = 3.0


def pick(label: int) -> tuple[str, bytes]:
    for name in sorted(os.listdir(DATA_DIR)):
        if not name.endswith(".parquet"):
            continue
        pf = pq.ParquetFile(os.path.join(DATA_DIR, name))
        for batch in pf.iter_batches(batch_size=64, columns=["audio", "label"]):
            rows = batch.to_pydict()
            for audio, row_label in zip(rows["audio"], rows["label"]):
                if int(row_label) == label:
                    return os.path.basename(audio["path"]), audio["bytes"]
    raise SystemExit(f"no clip with label {label} in {DATA_DIR}")


def convert(blob: bytes) -> np.ndarray:
    data, rate = sf.read(__import__("io").BytesIO(blob), dtype="float32", always_2d=True)
    x = data.mean(axis=1)
    if int(rate) != SR:
        g = gcd(int(rate), SR)
        x = resample_poly(x, SR // g, int(rate) // g).astype(np.float32)
    want = int(SECONDS * SR)
    if len(x) > want:  # centre crop: avoids leading silence
        start = (len(x) - want) // 2
        x = x[start:start + want]
    elif len(x) < want:
        x = np.pad(x, (0, want - len(x)))
    peak = float(np.max(np.abs(x))) or 1.0
    return (x / peak * 0.7).astype(np.float32)


def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    sources = {}
    for label, filename in ((0, "real_speech.wav"), (1, "fake_speech.wav")):
        source, blob = pick(label)
        sf.write(os.path.join(OUT_DIR, filename), convert(blob), SR, subtype="PCM_16")
        sources[filename] = source
        print(f"{filename:16s} <- {source}")

    with open(os.path.join(OUT_DIR, "ATTRIBUTION.txt"), "w", encoding="utf-8") as f:
        f.write(
            "Test fixtures from garystafford/deepfake-audio-detection (CC-BY-4.0),\n"
            "https://huggingface.co/datasets/garystafford/deepfake-audio-detection\n"
            "16 kHz mono, 3 s centre crop, peak-normalised.\n\n"
        )
        for filename, source in sources.items():
            f.write(f"{filename}: {source}\n")


if __name__ == "__main__":
    main()
